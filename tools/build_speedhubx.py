#!/usr/bin/env python3
"""Bundle src/speedhubx/*.luau into a single self-contained executor script at
src/SpeedHubX.luau.

Executor scripts must be fully standalone: one file, zero external requires.
The bundle registers every module in a tiny lazy registry and boots
`init` at the bottom, which starts the UI.

Usage:
    python3 tools/build_speedhubx.py            # write src/SpeedHubX.luau
    python3 tools/build_speedhubx.py --check    # exit 1 when the bundle is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "src" / "speedhubx"
OUTPUT = ROOT / "src" / "SpeedHubX.luau"

HEADER = """\
--!nocheck
--[[
    Speed Hub X — Version: 3.7.0 (single-file build)
    ================================================
    AUTO-GENERATED from src/speedhubx/*.luau — do not edit this file
    directly.  Rebuild with:

        python3 tools/build_speedhubx.py

    Standalone client-sided menu for Roblox script executors.
    Paste the whole file into your executor, or load it with:

        loadstring(game:HttpGet("<your raw URL to src/SpeedHubX.luau>"))()

    Layout (top to bottom): chrome pill -> window -> sidebar + pages,
    with the theme / icons / components / feature stubs bundled in.

    IMPORTANT — scope of this build:
        This is a faithful UI re-creation of the menu only.  Every
        gameplay feature callback (aim, farming, combat, movement,
        safe mode, automation, configuration persistence, ...) is an
        intentionally EMPTY stub in the Features modules.  Wire your
        own logic there.  The window chrome itself (drag, scaling,
        tab switching, toggle/dropdown visuals, RightControl hide,
        \"close\" button) is fully functional UI code.

    Controls:
        - Drag the title bar to move the window.
        - Drag the floating \"S\" tile to move it.
        - RightControl toggles the whole interface on/off.
        - The × button destroys the interface and disconnects everything.
]]
"""


def module_id(path: Path) -> str:
    return path.relative_to(SRC_DIR).as_posix()[: -len(".luau")]


def collect_sources() -> list[tuple[str, str]]:
    files = sorted(SRC_DIR.rglob("*.luau"))
    result = []
    for path in files:
        result.append((module_id(path), path.read_text(encoding="utf-8")))
    return result


def render(modules: list[tuple[str, str]]) -> str:
    parts: list[str] = [HEADER.rstrip("\n"), ""]
    parts.append("local __modules = {}")
    parts.append("local __cache = {}")
    parts.append("")
    parts.append("local function __register(id, factory)")
    parts.append("    __modules[id] = factory")
    parts.append("end")
    parts.append("")
    parts.append("local function __require(id)")
    parts.append("    local cached = __cache[id]")
    parts.append("    if cached ~= nil then")
    parts.append("        return cached")
    parts.append("    end")
    parts.append("    local factory = __modules[id]")
    parts.append('    assert(factory, ("[SpeedHubX] missing module: %s"):format(id))')
    parts.append("    local value = factory(__require)")
    parts.append("    __cache[id] = value")
    parts.append("    return value")
    parts.append("end")
    parts.append("")

    for mod_id, source in modules:
        parts.append(f'__register("{mod_id}", function(require)')
        parts.append(source.rstrip("\n"))
        parts.append("end)")
        parts.append("")

    parts.append('__require("init")')
    parts.append("")
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the bundle is up to date")
    args = parser.parse_args()

    modules = collect_sources()
    if not modules:
        print(f"error: no .luau sources found under {SRC_DIR}", file=sys.stderr)
        return 1

    output = render(modules)

    if args.check:
        existing = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if existing != output:
            print("error: src/SpeedHubX.luau is stale — run tools/build_speedhubx.py", file=sys.stderr)
            return 1
        print(f"PASS bundle up to date ({len(modules)} modules, {len(output)} bytes)")
        return 0

    OUTPUT.write_text(output, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} — {len(modules)} modules, {len(output)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
